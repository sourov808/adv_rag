"""Run offline Ragas evaluation for the indexed Wizard of Oz document."""

import asyncio
import json
import os
from pathlib import Path

from dotenv import load_dotenv
from openai import AsyncOpenAI
from ragas.embeddings import OpenAIEmbeddings
from ragas.llms import llm_factory
from ragas.metrics.collections import (
    AnswerRelevancy,
    Faithfulness,
    ContextPrecision,
    ContextRecall,
)

from rag.embeddings import embedding_model_name, get_embedding_client
from rag.generation import (
    create_openai_model,
    generate_answer_async,
    get_openai_api_key,
)
from rag.retrieval import build_context, retrieve_chunks
from rag.vector_store import collection_count, open_collection

load_dotenv()

evaluation_file = Path("data/evaluation.json")
results_file = Path("data/evaluation_results.json")
report_file = Path("data/evaluation_report.md")
evaluator_model_name = os.getenv("OPENAI_EVALUATION_MODEL", "gpt-4o-mini")


def load_questions():
    """Read the evaluation questions and reference answers."""
    with evaluation_file.open(encoding="utf-8") as file:
        return json.load(file)


def create_evaluator():
    """Create the LLM and embedding wrappers Ragas needs for scoring."""
    client = AsyncOpenAI(api_key=get_openai_api_key())
    evaluator_llm = llm_factory(
        evaluator_model_name,
        provider="openai",
        client=client,
        temperature=0,
    )
    evaluator_embeddings = OpenAIEmbeddings(client, model=embedding_model_name)

    return {
        "faithfulness": Faithfulness(llm=evaluator_llm),
        "answer_relevancy": AnswerRelevancy(
            llm=evaluator_llm,
            embeddings=evaluator_embeddings,
            strictness=1,
        ),
        "context_precision": ContextPrecision(llm=evaluator_llm),
        "context_recall": ContextRecall(llm=evaluator_llm),
    }


async def score_question(question, model, collection, evaluator, llm):
    """Retrieve, answer, and score one evaluation question."""
    matches = retrieve_chunks(question["question"], model, collection)
    contexts = [match["text"] for match in matches]
    context = build_context(matches)
    answer, usage = await generate_answer_async(llm, question["question"], context)

    scores = {
        "faithfulness": (
            await evaluator["faithfulness"].ascore(
                user_input=question["question"],
                response=answer,
                retrieved_contexts=contexts,
            )
        ).value,
        "answer_relevancy": (
            await evaluator["answer_relevancy"].ascore(
                user_input=question["question"],
                response=answer,
            )
        ).value,
        "context_precision": None,
        "context_recall": None,
    }

    if question["should_answer"]:
        scores["context_precision"] = (
            await evaluator["context_precision"].ascore(
                user_input=question["question"],
                reference=question["reference"],
                retrieved_contexts=contexts,
            )
        ).value
        scores["context_recall"] = (
            await evaluator["context_recall"].ascore(
                user_input=question["question"],
                retrieved_contexts=contexts,
                reference=question["reference"],
            )
        ).value

    return {
        "id": question["id"],
        "question": question["question"],
        "reference": question["reference"],
        "should_answer": question["should_answer"],
        "answer": answer,
        "sources": [
            f"{match['metadata']['source']}, page {match['metadata']['page']}"
            for match in matches
        ],
        "scores": scores,
        "usage": usage,
    }


def average_scores(results):
    """Average each metric while skipping metrics not used for unanswerable questions."""
    averages = {}

    for metric in [
        "faithfulness",
        "answer_relevancy",
        "context_precision",
        "context_recall",
    ]:
        values = [result["scores"][metric] for result in results]
        values = [value for value in values if value is not None]
        averages[metric] = sum(values) / len(values) if values else None

    return averages


def total_usage(results):
    """Add token use from the answers generated by the RAG application."""
    totals = {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}

    for result in results:
        for name in totals:
            totals[name] += result["usage"][name]

    return totals


def save_markdown_report(report):
    """Save a readable evaluation summary that is easy to share."""
    lines = [
        "# RAG Evaluation Results",
        "",
        "## Average scores",
        "",
        "| Metric | Score |",
        "| --- | ---: |",
    ]

    for name, score in report["averages"].items():
        label = name.replace("_", " ").title()
        value = f"{score:.3f}" if score is not None else "N/A"
        lines.append(f"| {label} | {value} |")

    usage = report["answer_token_usage"]
    lines.extend(
        [
            "",
            "## Answer token usage",
            "",
            f"- Input tokens: {usage['prompt_tokens']}",
            f"- Output tokens: {usage['completion_tokens']}",
            f"- Total tokens: {usage['total_tokens']}",
            "",
            "## Per-question scores",
            "",
            "| ID | Faithfulness | Answer relevancy | Context precision | Context recall |",
            "| --- | ---: | ---: | ---: | ---: |",
        ]
    )

    for result in report["results"]:
        scores = result["scores"]
        values = [
            result["id"],
            f"{scores['faithfulness']:.3f}",
            f"{scores['answer_relevancy']:.3f}",
            score_or_na(scores["context_precision"]),
            score_or_na(scores["context_recall"]),
        ]
        lines.append("| " + " | ".join(values) + " |")

    report_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def score_or_na(score):
    """Format an optional evaluation score for a Markdown table."""
    return f"{score:.3f}" if score is not None else "N/A"


async def run_evaluation():
    """Evaluate every question and save the completed report."""
    collection = open_collection()

    if collection_count(collection) == 0:
        raise ValueError(
            "The collection is empty. Index data/wizard_of_oz.txt in the Streamlit app first."
        )

    embedding_client = get_embedding_client()
    evaluator = create_evaluator()
    llm = create_openai_model()
    results = []

    for question in load_questions():
        print(f"Evaluating {question['id']}: {question['question']}")
        result = await score_question(question, embedding_client, collection, evaluator, llm)
        results.append(result)

    report = {
        "averages": average_scores(results),
        "answer_token_usage": total_usage(results),
        "results": results,
    }

    with results_file.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=2)
    save_markdown_report(report)

    print("\nAverage scores")
    for metric, score in report["averages"].items():
        if score is not None:
            print(f"{metric}: {score:.3f}")

    usage = report["answer_token_usage"]
    print(
        f"\nAnswer tokens: {usage['prompt_tokens']} input | "
        f"{usage['completion_tokens']} output | {usage['total_tokens']} total"
    )
    print(f"Saved results to {results_file}")
    print(f"Saved shareable report to {report_file}")


if __name__ == "__main__":
    asyncio.run(run_evaluation())
